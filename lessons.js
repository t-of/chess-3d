const START = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1';

// 定跡: rows の 1 行は [q, 自分の手（配列なら全部正解）, 相手の手（なければ null）, why, bad]。
// 行き先の升は最初は光らせず、2 回まちがえたら光る（hintSq）。
const sqName = (u) => u.slice(2, 4);
const opening = (q, rows, side = 'w', pre) => {
  const mine = rows.map((r) => [].concat(r[1]));
  return {
    q, fen: START, goal: 'steps', side, ...(pre && { pre }), hint: '光った升が行き先',
    steps: rows.map((r, i) => ({
      q: i ? r[0] : `${q}。${r[0]}`, ok: mine[i], ...(r[2] && { reply: r[2] }), why: r[3],
      hintSq: [sqName(mine[i][0])], ...(r[4] && { bad: r[4] }),
    })),
    sol: mine.map((m) => m[0]),
  };
};

